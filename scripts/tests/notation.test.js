const assert=require('node:assert/strict');
const N=require('../../static/pianoroll/core/notation.js');
const note=(id,pitch,startBeat,durationBeat)=>({id,pitch,startBeat,durationBeat,velocity:90});
const score=notes=>({version:2,time_signature:'4/4',tracks:[{id:'t1',name:'Melody',notes}]});
const s=score([note('a',60,0,1),note('b',64,0,1),note('c',67,0.5,2),note('d',62,3,3)]);
const before=JSON.stringify(s), m=N.project(s,120,{grid:4});
assert.equal(JSON.stringify(s),before,'view projection cannot mutate notes');
assert.equal(m.count,4);assert.equal(m.bars,2);assert.equal(m.lanes.length,2,'overlapping voices retained');
assert.equal(m.lanes[0].bars[0][0].refs.length,2,'chord retained');
const d=m.lanes.flatMap(l=>l.bars.flat()).filter(e=>e.refs.some(r=>r.noteId==='d'));
assert(d.some(e=>e.tieIn) && d.some(e=>e.tieOut),'bar-crossing notes tied');
assert.equal(d.reduce((v,e)=>v+e.ticks,0),48,'tied durations conserved');
for(const lane of m.lanes)for(const bar of lane.bars)assert.equal(bar.reduce((v,e)=>v+e.ticks,0),64,'every measure filled by notes and rests');
const irregular=score([note('a',60,.12,.47)]);assert.equal(N.project(irregular,120,{}).approximated,1);assert.equal(irregular.tracks[0].notes[0].durationBeat,.47);
const empty=N.project(score([]),120,{});assert(empty.lanes[0].bars[0].every(e=>e.rest));
const refs=[{trackId:'t1',noteId:'a'}];const edited=N.edit(s,refs,{pitchDelta:1,durationBeat:.5},120);
assert.equal(edited.tracks[0].notes[0].pitch,61);assert.equal(edited.tracks[0].notes[0].durationBeat,.5);assert.deepEqual(edited.tracks[0].notes.slice(1),s.tracks[0].notes.slice(1));
assert.equal(JSON.stringify(s),before);
const sec={version:1,time_signature:'6/8',tracks:[{id:'t1',notes:[{id:'a',pitch:60,start:.25,duration:.5,velocity:90}]}]};
assert.equal(N.project(sec,120,{}).barTicks,48);assert.equal(N.project(sec,60,{}).lanes[0].events[0].from,4);
assert.equal(N.edit(sec,refs,{startBeat:2,durationBeat:1},120).tracks[0].notes[0].start,1);
assert.equal(N.edit(sec,refs,{startBeat:2,durationBeat:1},120).tracks[0].notes[0].duration,.5);
assert.deepEqual(N.spelling(61,'C'),{degree:1,accidental:'#',octave:0,key:'c/4',alter:'#'});
assert.equal(N.spelling(70,'F').degree,4);assert.equal(N.spelling(70,'F').key,'b/4');
assert.equal(N.spelling(70,'F').alter,'b');assert.equal(N.spelling(60,'G').degree,4);
assert.equal(N.preferences({view:'bad',key:'bad'}).view,'roll');
assert.throws(()=>N.project(score([note('a',60,0,50000)]),120,{}),/too large/);
assert.throws(()=>N.edit(s,refs,{pitch:NaN},120),/Invalid/);
assert.throws(()=>N.project(score([note('a',60,-1,1)]),120,{}),/Invalid/);
// Every fragment is traceable, including multiple voices and cross-bar ties.
const seen=new Set(m.lanes.flatMap(l=>l.bars.flat()).flatMap(e=>e.refs.map(r=>r.noteId)));
assert.deepEqual([...seen].sort(),['a','b','c','d']);
const original=score([note('a',60,.123456789,.456789123),note('b',62,1,1)]);
const oldDraft={tracks:[{id:'t1',notes:[{id:'a',pitch:60,start:.074074,duration:.274073,velocity:90},{id:'b',pitch:62,start:.6,duration:.6,velocity:90}]}]};
const newDraft=JSON.parse(JSON.stringify(oldDraft));newDraft.tracks[0].notes[0]._trackId='t1';newDraft.tracks[0].notes[1].pitch=64;
const rounded=score([note('a',60,.123457,.456788),note('b',64,1,1)]);
const reconciled=N.reconcileSavedScore(original,oldDraft,newDraft,rounded);
assert.deepEqual(reconciled.tracks[0].notes[0],original.tracks[0].notes[0],'untouched note retains exact beat precision and ignores UI annotations');
assert.equal(reconciled.tracks[0].notes[1].pitch,64,'changed note survives save');
assert.equal(N.transposeStaff(64,1,'C'),65,'E to F is one staff position');
assert.equal(N.transposeStaff(64,1,'G'),66,'G major uses F sharp');
assert.equal(N.transposeStaff(60,-1,'C'),59,'cross octave downward');
assert.equal(N.transposeStaff(61,1,'C'),63,'preserve chromatic offset');
assert.equal(N.transposeStaff(70,1,'F'),72,'B flat to C in F major');
for(const key of Object.keys(N.KEYS))for(let pitch=0;pitch<=127;pitch++)assert.equal(N.transposeStaff(pitch,0,key),pitch);
assert.equal(N.transposeStaff(0,-100,'C'),0);assert.equal(N.transposeStaff(127,100,'C'),127);
console.log('PASS notation: immutable projection, timing, voices, chords, ties, rests, spelling, targeted edits, bounds, staff pitch movement');
